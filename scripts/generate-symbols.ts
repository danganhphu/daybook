const output = "src/shared/ui/icon/icons.tsx";

// The path a symbol draws, refusing anything else: the component renders exactly one path on a 24-unit grid
function pathOf(name: string) {
  const data = getIconData(icons, name);
  if (data === null) {
    throw new Error(`Material Symbols has no ${name}`);
  }
  const svg = iconToSVG(data);
  const path = /^<path fill="currentColor" d="([^"]+)"\/>$/.exec(svg.body)?.[1];
  if (svg.attributes.viewBox !== "0 0 24 24" || path === undefined) {
    throw new Error(`${name} is not one path on a 24-unit grid: ${svg.body}`);
  }
  return path;
}

function component(name: string) {
  const pascal = name.replaceAll(/(?:^|-)(\w)/g, (_, letter: string) => letter.toUpperCase());
  const outlinePath = pathOf(`${name}-outline-rounded`);
  const filledPath = pathOf(`${name}-rounded`);
  const filled = filledPath === outlinePath ? "" : ` filledPath="${filledPath}"`;
  return (
    `export function ${pascal}Icon(props: IconProps) {\n` +
    `  return <MaterialSymbol {...props} outlinePath="${outlinePath}"${filled} />;\n` +
    `}\n`
  );
}

writeFileSync(
  output,
  `// Generated by \`pnpm symbols\` from Material Symbols Rounded (Apache-2.0, Google). Change the list in\n` +
    `// scripts/generate-symbols.ts and run it again instead of editing this file.\n` +
    `import type { IconProps } from "./icon";\n` +
    `import { MaterialSymbol } from "./material-symbol";\n\n` +
    names.map(component).join("\n"),
);
